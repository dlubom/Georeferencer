"""Jawna aktualizacja locka w etapie dependency-tools (patrz ci/README.md)."""

import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
source = ROOT / "pipeline/requirements.txt"
with tempfile.TemporaryDirectory() as directory:
    report = Path(directory) / "dependencies.json"
    subprocess.run([
        sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
        "--only-binary=:all:", "--report", str(report), "-r", str(source),
    ], check=True)
    packages = json.loads(report.read_text())["install"]

lines = [f"# source-sha256: {hashlib.sha256(source.read_bytes()).hexdigest()}",
         "# Linux/amd64, Python 3.12; generated by ci/resolve-requirements.py."]
for package in sorted(packages, key=lambda item: item["metadata"]["name"].lower()):
    metadata = package["metadata"]
    digest = package["download_info"]["archive_info"]["hashes"]["sha256"]
    lines.append(f"{metadata['name']}=={metadata['version']} --hash=sha256:{digest}")
(ROOT / "ci/requirements.lock").write_text("\n".join(lines) + "\n")
